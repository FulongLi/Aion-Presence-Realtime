import { mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { join, resolve } from "node:path";
import { build } from "esbuild";

/**
 * Builds the interactive card runtime (src/presence-core/cards/runtime: Three.js WebGL and the card applications) into
 * one sandboxed HTML document, exactly as the Plugin's scripts/build.ts does, and writes it as the module the Presence
 * surface imports as "aion:card-runtime" (next.config.ts aliases it). The output is generated, not committed.
 *
 *   npm run presence:cards     (runs before `next dev` and `next build`)
 */
const REPO_ROOT = resolve(import.meta.dirname, "..", "..");
const src = (path: string) => join(REPO_ROOT, "src", "presence-core", path);
export const CARD_RUNTIME_MODULE = join(REPO_ROOT, ".generated", "card-runtime.js");

const result = await build({
  entryPoints: [src("cards/runtime/main.ts")], bundle: true, minify: true, legalComments: "none", logLevel: "warning", sourcemap: false,
  write: false, platform: "browser", format: "iife", target: ["chrome120", "safari17", "firefox121"], absWorkingDir: REPO_ROOT,
});
const script = result.outputFiles[0].text;
const html = readFileSync(src("cards/runtime/index.html"), "utf8")
  .replace("/*__STYLES__*/", () => readFileSync(src("cards/runtime/styles.css"), "utf8"))
  // A literal "</script" inside the bundle would end the inline script early.
  .replace("/*__SCRIPT__*/", () => script.replace(/<\/script/gi, "<\\/script"));
mkdirSync(join(REPO_ROOT, ".generated"), { recursive: true });
writeFileSync(CARD_RUNTIME_MODULE, `// Generated by scripts/presence/card-runtime.ts from src/presence-core/cards/runtime. Do not edit.\nexport default ${JSON.stringify(html)};\n`);
console.log(`  card runtime  ${(html.length / 1024).toFixed(0)} KB → .generated/card-runtime.js`);
